#!/usr/bin/env bash
# Regenerates web/shaders/ from shaders/*.hlsl. Nothing in there is written by hand:
#
#   benchmark.frag   the benchmark workload (rtx-pathtracer.hlsl with BENCHMARK=1) as GLSL ES 3.00
#   <id>.frag        every wallpaper shader as GLSL ES 3.00, for the gallery
#   manifest.json    id, name, tags and settings of those shaders
#
#   web/build.sh [--allow-missing] [BINARY [OUT_DIR]]
#
# BINARY is the wallpepper binary (default <repository>/build/wallpepper, built if missing), OUT_DIR where to
# write (default web/shaders). A shader that does not compile as GLSL ES is an error, because the gallery
# would silently lose it; --allow-missing leaves it out instead. The old output is replaced only when the new
# one is complete.
#
# Needs what building wallpepper needs (build-essential cmake) plus EGL with OpenGL ES 3 (Mesa: libegl1
# libgl1-mesa-dri), so that each translation is tried on a real GLSL ES compiler.
set -eu

allow_missing=false
if [ "${1:-}" = "--allow-missing" ]; then
    allow_missing=true
    shift
fi
root=$(cd "$(dirname "$0")/.." && pwd)
wallpepper=${1:-$root/build/wallpepper}
out=${2:-$root/web/shaders}
export WALLPEPPER_SHADERS=$root/shaders

if [ ! -x "$wallpepper" ]; then
    cmake -S "$root/linux" -B "$root/build" >/dev/null
    cmake --build "$root/build" -j "$(nproc)" >/dev/null
fi

new=$out.new
rm -rf "$new"
mkdir -p "$new"
trap 'rm -rf "$new"' EXIT

# translate ID FILE [OPTION...]: the GLSL ES translation with a note on its second line. (The first line has to
# be `#version`: browsers accept nothing in front of it, not even a comment.)
translate() {
    local id=$1 file=$2
    shift 2
    "$wallpepper" translate --es "$id" "$@" |
        sed "1a // Generated by web/build.sh from shaders/$id.hlsl. Do not edit." >"$new/$file"
}

"$wallpepper" check --es rtx-pathtracer --set BENCHMARK=1 >/dev/null
translate rtx-pathtracer benchmark.frag --set BENCHMARK=1

gallery=()
missing=()
for path in "$WALLPEPPER_SHADERS"/*.hlsl; do
    id=$(basename "$path" .hlsl)
    # Windows Terminal text effects have nothing to show without a terminal.
    if "$wallpepper" list "$id" | grep -q 'terminal-only'; then continue; fi
    if "$wallpepper" check --es "$id" >/dev/null 2>&1; then
        translate "$id" "$id.frag"
        gallery+=("$id")
    else
        missing+=("$id")
    fi
done
"$wallpepper" list --json "${gallery[@]}" >"$new/manifest.json"

if [ "${#missing[@]}" -gt 0 ]; then
    echo "not compiling as GLSL ES 3.00 (see: wallpepper check --es ${missing[*]}): ${missing[*]}" >&2
    $allow_missing || exit 1
fi
rm -rf "$out"
mv "$new" "$out"
echo "$out: benchmark.frag and ${#gallery[@]} gallery shaders"
