#!/usr/bin/env python3
"""Writes docs/SHADERS.md: one row per shader with its name, tags, number of settings and description."""
import pathlib, re

root = pathlib.Path(__file__).resolve().parent.parent
rows = []
for path in sorted((root / "shaders").glob("*.hlsl")):
    lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    name, tags, text = path.stem.replace("-", " ").title(), "", []
    for i, line in enumerate(lines[:12]):
        body = line.strip()[2:].strip() if line.strip().startswith("//") else None
        if body is None:
            if text or i > 3:
                break
            continue
        if body.lower().startswith("@name"):
            name = body.split(":", 1)[1].strip()
        elif body.lower().startswith("@tags"):
            tags = body.split(":", 1)[1].strip()
        elif body.startswith("@"):
            continue
        elif tags and not re.search(r"original by|edit by|ported|licen[cs]e|cc0|wallpepper edit|^-+$", body, re.I):
            text.append(body)
    text = " ".join(text)
    settings = sum(1 for l in lines if re.match(r"#define\s+[A-Z0-9_]+\s+-?[0-9.]+\s*//", l))
    rows.append((name, path.name, tags, settings, text))

out = ["# Bundled shaders", "", f"{len(rows)} shaders. Generated by `tools/list_shaders.py`.", "",
       "| Name | File | Tags | Settings | What you see |", "| --- | --- | --- | ---: | --- |"]
out += [f"| {n} | `{f}` | {t} | {s} | {d} |" for n, f, t, s, d in rows]
(root / "docs" / "SHADERS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(f"{len(rows)} shaders -> docs/SHADERS.md")
